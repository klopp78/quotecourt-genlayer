import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const page = readFileSync("site-static/index.html", "utf8");
const client = readFileSync("site-static/main.ts", "utf8");
for (const marker of ["Authorized executor wallet", "Submit purchase proof", "Verify completion", "Public purchase-proof URL", "FINALIZED RECEIPT"]) assert.ok(page.includes(marker), `missing visible v2 flow control: ${marker}`);
for (const method of ["register_quote_request", "assess_provider_quotes", "challenge_quote_decision", "resolve_quote_challenge", "finalize_purchase_authorization", "execute_authorized_purchase", "verify_purchase_completion"]) assert.ok(client.includes(method), `missing GenLayer v2 method: ${method}`);
assert.ok(client.includes("TransactionStatus.FINALIZED"), "writes must wait for finalization");
assert.ok(client.includes("ExecutionResult.FINISHED_WITH_RETURN"), "writes must verify execution result");
assert.ok(client.includes("readBack"), "writes must verify resulting contract state");
console.log("QuoteCourt v2 finalized frontend flow checks passed");
